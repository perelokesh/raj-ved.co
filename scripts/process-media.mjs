// Builds the asset manifest: measures every image in public/media, generates a
// ~24px blur placeholder, writes src/content/assets.ts and CREDITS.md.
// Run after scripts/generate-placeholders.mjs (or when real media replaces it).
// Run: node scripts/process-media.mjs
import sharp from "sharp";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const MEDIA = path.join(ROOT, "public/media");

const credits = JSON.parse(await readFile(path.join(MEDIA, "CREDITS.json"), "utf8"));
const creditByFile = new Map(credits.map((c) => [c.file, c]));

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (/\.(jpe?g|png|webp)$/i.test(entry.name)) out.push(full);
  }
  return out;
}

const files = (await walk(MEDIA)).sort();
const assets = [];
for (const abs of files) {
  const rel = path.relative(ROOT, abs);
  const meta = await sharp(abs).metadata();
  const blurBuf = await sharp(abs).resize(24).blur(1).jpeg({ quality: 40 }).toBuffer();
  const credit = creditByFile.get(rel);
  const slug = path.basename(abs, path.extname(abs));
  assets.push({
    id: slug,
    src: "/" + path.relative(path.join(ROOT, "public"), abs),
    width: meta.width,
    height: meta.height,
    blur: `data:image/jpeg;base64,${blurBuf.toString("base64")}`,
    placeholder: true,
    credit: credit
      ? { author: credit.author, source: credit.source, licence: credit.licence, fetched: credit.fetched }
      : { author: "Unknown", source: "unknown", licence: "unknown", fetched: "" },
  });
}

const header = `// GENERATED by scripts/process-media.mjs. Do not edit by hand.
// Every slot has placeholder: true until real media replaces it (npm run assets:report).

export type AssetCredit = {
  author: string;
  source: string;
  licence: string;
  fetched: string;
};

export type Asset = {
  id: string;
  src: string;
  width: number;
  height: number;
  blur: string;
  placeholder: boolean;
  credit: AssetCredit;
};

export const assets: Record<string, Asset> = {
`;

const body = assets
  .map((a) => `  ${JSON.stringify(a.id)}: ${JSON.stringify(a, null, 2).replace(/\n/g, "\n  ")},`)
  .join("\n");

await writeFile(path.join(ROOT, "src/content/assets.ts"), header + body + "\n};\n");
await writeFile(path.join(MEDIA, "manifest.json"), JSON.stringify(assets, null, 2) + "\n");

const md = [
  "# Media credits",
  "",
  "Generated from `public/media/CREDITS.json`. Every asset here is a synthetic placeholder.",
  "",
  "| File | Size | Licence | Source |",
  "| --- | --- | --- | --- |",
  ...credits.map((c) => `| \`${c.file.replace("public/media/", "")}\` | ${c.width}x${c.height} | ${c.licence} | ${c.source} |`),
  "",
].join("\n");
await writeFile(path.join(MEDIA, "CREDITS.md"), md);

console.log(`Manifest: ${assets.length} assets -> src/content/assets.ts`);
